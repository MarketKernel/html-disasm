/**
 * Gives the Rust core the WebAssembly instructions: reads the table of
 * src/core/wasm/opcodes.ts (the one source, which the page's reference reads
 * too) and writes it as static data,
 *
 *   crates/core/src/wasm/opcodes_table.rs
 *
 *   node tools/wasm-opcodes.mjs           write it
 *   node tools/wasm-opcodes.mjs --check   fail if it is not what opcodes.ts gives (npm test)
 *
 * The core then has the table in its read-only data from the start: nothing is
 * built on first use, and the module carries rows instead of the code that made
 * them. `cargo test -p disasm-core` checks the table against the decoder's
 * vectors; run this again after any change to opcodes.ts.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { load, root } from './load.mjs';

const { allOps } = await load('core/wasm/opcodes');
const ops = allOps();

const GROUPS = { control: 'Control', reference: 'Reference', parametric: 'Parametric', variable: 'Variable', table: 'Table', memory: 'Memory', numeric: 'Numeric', vector: 'Vector', atomic: 'Atomic', aggregate: 'Aggregate', exception: 'Exception' };
const PREFIXES = [0xfb, 0xfc, 0xfd, 0xfe];

/** How many values the signature takes and pushes (`i32 i32 > i32`): None when it depends on the module. */
function fixed(sig) {
  if (!sig) return 'None';
  const [left, right = ''] = sig.split('>');
  const count = (side) => side.split(/\s+/).filter(Boolean).length;
  return `Some((${count(left)}, ${count(right)}))`;
}

const hex = (n) => `0x${n.toString(16)}`;
const rows = ops.map((o) => {
  if (!(o.group in GROUPS)) throw new Error(`${o.name}: no group ${o.group}`);
  return `    op(${hex(o.code)}, ${JSON.stringify(o.name)}, ${o.imm}, ${JSON.stringify(o.sig)}, ${GROUPS[o.group]}, ${hex(o.flags)}, ${o.align}, ${o.size}, ${fixed(o.sig)}),`;
});

// Index + 1 into OPS by opcode, 0 for none: the single bytes, then each prefix's own opcodes.
const single = new Array(256).fill(0);
const prefixed = PREFIXES.map(() => []);
ops.forEach((o, i) => {
  const prefix = o.code >>> 16;
  const sub = o.code & 0xffff;
  if (!prefix) single[sub] = i + 1;
  else {
    const table = prefixed[PREFIXES.indexOf(prefix)];
    if (!table) throw new Error(`${o.name}: no prefix ${hex(prefix)}`);
    while (table.length <= sub) table.push(0);
    table[sub] = i + 1;
  }
});
const numbers = (list) => {
  const lines = [];
  for (let i = 0; i < list.length; i += 24) lines.push(`    ${list.slice(i, i + 24).join(', ')},`);
  return lines.join('\n');
};

const out = `//! The WebAssembly instructions, generated by tools/wasm-opcodes.mjs from
//! src/core/wasm/opcodes.ts. Do not edit: change opcodes.ts and run the tool again.

use super::opcodes::{op, Group::*, OpInfo};

/// Every instruction, in the order opcodes.ts defines them.
#[rustfmt::skip]
pub(super) static OPS: [OpInfo; ${ops.length}] = [
${rows.join('\n')}
];

/// Index + 1 into [\`OPS\`] by the single-byte opcode, 0 for none.
#[rustfmt::skip]
pub(super) static SINGLE: [u16; 256] = [
${numbers(single)}
];

/// Index + 1 into [\`OPS\`] by the opcode after each prefix (0xfb, 0xfc, 0xfd, 0xfe), 0 for none.
#[rustfmt::skip]
pub(super) static PREFIXED: [&[u16]; 4] = [
${prefixed.map((t) => `    &[\n    ${numbers(t).replace(/\n/g, '\n    ')}\n    ],`).join('\n')}
];
`;
const file = join(root, 'crates', 'core', 'src', 'wasm', 'opcodes_table.rs');
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== out) {
    console.error('crates/core/src/wasm/opcodes_table.rs is not what src/core/wasm/opcodes.ts gives: run node tools/wasm-opcodes.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(file, out);
  console.log(`crates/core/src/wasm/opcodes_table.rs, ${ops.length} instructions`);
}
