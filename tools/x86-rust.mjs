/**
 * Gives the Rust core the x86 tables: reads src/core/x86/tables.ts (made by
 * tools/x86-index.mjs) and writes
 *
 *   crates/core/src/x86/tables.rs   the constants (contexts, print methods, aliases…)
 *   crates/core/src/x86/tables.bin  the blob, still deflated (only the base64 is undone)
 *
 *   node tools/x86-rust.mjs
 *
 * The Rust decoder embeds the blob with include_bytes! and inflates it once,
 * on first use, as the TypeScript one does; the two read the very same bytes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './load.mjs';

const source = readFileSync(join(root, 'src', 'core', 'x86', 'tables.ts'), 'utf8');

/** The value of `export const NAME…= value;`, as JSON (the TypeScript types and `as const` dropped). */
function constant(name) {
  const match = new RegExp(`^export const ${name}(?::[^=]*)? = (.*?)(?: as const)?;$`, 'm').exec(source);
  if (!match) throw new Error(`tables.ts: no ${name}`);
  const text = match[1];
  return JSON.parse(text.startsWith("'") ? `"${text.slice(1, -1)}"` : text);
}

const LLVM_VERSION = constant('LLVM_VERSION');
const CONTEXT_COUNT = constant('CONTEXT_COUNT');
const PRINT_METHODS = constant('PRINT_METHODS');
const SUFFIXES = constant('SUFFIXES');
const ALIASES = constant('ALIASES');
const PARTS = constant('PARTS');
const XRELEASE = constant('XRELEASE');
const XACQUIRE = constant('XACQUIRE');
const SPECIAL = constant('SPECIAL');
const BLOB = constant('BLOB');

const str = (s) => JSON.stringify(s);
const list = (items) => `[${items.map(str).join(', ')}]`;

const rs = `//! The x86 decoding tables' constants, generated by tools/x86-rust.mjs from
//! src/core/x86/tables.ts (itself generated by tools/x86-index.mjs from the X86
//! target description of LLVM ${LLVM_VERSION}). Do not edit: run the tools again.
//!
//! The tables themselves are tables.bin, the blob of tables.ts still deflated;
//! decode.rs inflates it once, on first use.
//!
//! LLVM is under the Apache License 2.0 with LLVM Exceptions. What is kept here
//! are facts about the encoding: which instruction each opcode selects in each
//! context, where its operands are encoded, and the Intel syntax of each.

pub const LLVM_VERSION: &str = ${str(LLVM_VERSION)};
pub const CONTEXT_COUNT: usize = ${CONTEXT_COUNT};
pub const PRINT_METHODS: [&str; ${PRINT_METHODS.length}] = ${list(PRINT_METHODS)};
pub const SUFFIXES: [&str; ${SUFFIXES.length}] = ${list(SUFFIXES)};
/// (instruction, [(operand, value)…], text): printed as the text when its immediates have those values.
pub type Alias = (u32, &'static [(usize, i64)], &'static str);
pub const ALIASES: [Alias; ${ALIASES.length}] = [${ALIASES.map(([id, conds, text]) => `(${id}, &[${conds.map(([at, value]) => `(${at}, ${value})`).join(', ')}], ${str(text)})`).join(', ')}];
/// The parts of the blob, in order.
pub const PARTS: [&str; ${PARTS.length}] = ${list(PARTS)};
/// What rep and repne print as before a locked instruction or an xchg (they are not in the tables).
pub const XRELEASE: &str = ${str(XRELEASE)};
pub const XACQUIRE: &str = ${str(XACQUIRE)};
/// Instructions the decoder treats specially, by LLVM's name.
pub mod special {
${Object.entries(SPECIAL).map(([name, id]) => `    pub const ${name}: u32 = ${id};`).join('\n')}
}
/// The tables, deflated (raw deflate, as tables.ts keeps them in base64).
pub static BLOB: &[u8] = include_bytes!("tables.bin");
`;

const dir = join(root, 'crates', 'core', 'src', 'x86');
writeFileSync(join(dir, 'tables.rs'), rs);
writeFileSync(join(dir, 'tables.bin'), Buffer.from(BLOB, 'base64'));
console.log(`crates/core/src/x86/tables.rs, tables.bin (${Buffer.from(BLOB, 'base64').length.toLocaleString()} bytes)`);
